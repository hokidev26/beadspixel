function cellAt(point) {
  const grid = appState.grid, cam = appState.camera;
  if (!grid) return -1;
  const x = Math.floor((point.x - cam.ox) / cam.cell);
  const y = Math.floor((point.y - cam.oy) / cam.cell);
  if (x < 0 || y < 0 || x >= grid.w || y >= grid.h) return -1;
  return y * grid.w + x;
}

